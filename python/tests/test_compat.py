def test_line_key_matches_summary_py() -> None:
    assert fv.line_key("11(a)(i)") == "line_11ai"
    assert fv.line_key("11(a)(ii)") == "line_11aii"
    assert fv.line_key("30(a)(ii)") == "line_30aii"
    assert fv.line_key("6(b)") == "line_6b"
    assert fv.line_key("38") == "line_38"


def test_summary_column_a_equals_the_golden_expected_json() -> None:
    expected = {k: Decimal(v) for k, v in json.loads((GOLDEN / "f3x.expected_column_a.json").read_text()).items()}
    got = fv.summary_column_a(golden("f3x"))
    assert got == expected
    assert all(isinstance(v, Decimal) for v in got.values())
    # The values FECfile+'s test_calculate_summary_column_a asserts.
    assert got["line_11ai"] == Decimal("10000.23")
    assert got["line_11aii"] == Decimal("3.77")
    assert got["line_15"] == Decimal("2125.79")
    assert got["line_24"] == Decimal("151.00")
    assert got["line_25"] == Decimal("133.00")
    assert got["line_28d"] == Decimal("604.50")
    # The five lines FECfile+ stubs to zero, derived from H3/H4 here.
    assert got["line_18c"] == Decimal("1000.00")
    assert got["line_21ai"] == Decimal("330.00")
    assert got["line_21aii"] == Decimal("670.00")
    assert got["line_30ai"] == got["line_30aii"] == 0


def test_summary_column_a_recomputes_from_the_schedules_not_the_cover() -> None:
    off = fv.summary_column_a(golden("f3x_cover_off_by_one_cent"))
    assert off == fv.summary_column_a(golden("f3x")), "the cover's cent is ignored"


def test_summary_column_a_on_f3_and_f3p_uses_their_line_labels() -> None:
    f3 = fv.summary_column_a(golden("f3"))
    assert {"line_11ai", "line_11aii", "line_13a", "line_17", "line_20a", "line_23", "line_27"} <= set(f3)
    assert f3["line_11ai"] == Decimal("2500.00") and f3["line_11aii"] == Decimal("150.00")
    f3p = fv.summary_column_a(golden("f3p"))
    assert {"line_17ai", "line_17aii", "line_18", "line_23", "line_28a", "line_6", "line_10"} <= set(f3p)
    assert f3p["line_17ai"] == Decimal("3300.00") and f3p["line_6"] == Decimal("250.00")


def test_summary_column_a_rejects_forms_without_rules() -> None:
    with pytest.raises(hardmoney.UnsupportedForm):
        fv.summary_column_a(golden("f24"))
